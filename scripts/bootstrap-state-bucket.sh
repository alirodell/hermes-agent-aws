#!/usr/bin/env bash
# One-time (idempotent) setup of the S3 bucket that holds Terraform state, plus terraform/backend.hcl.
#
#   NAME=hermes-agent scripts/bootstrap-state-bucket.sh
#
# NAME must match the `name` Terraform variable (default hermes-agent). The bucket is
# <NAME>-tfstate-<account-id>-<region>, unless STATE_BUCKET names an existing one (e.g. a setup
# created before this naming scheme). Its name goes into the gitignored terraform/backend.hcl,
# so the account ID never lands in the repo.
#
# Deliberately separate from the agent's data bucket: the instance role can read and write that
# one, so state stored there could be read or tampered with by the agent. Only your admin
# identity can reach this bucket. It is created outside Terraform because Terraform can't keep
# its state in a bucket it has yet to create. Safe to re-run; it only (re)applies settings.
set -euo pipefail

NAME="${NAME:-hermes-agent}"
REGION="${REGION:-us-east-1}"
ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)"
BUCKET="${STATE_BUCKET:-$NAME-tfstate-$ACCOUNT_ID-$REGION}"
BACKEND_FILE="$(cd "$(dirname "$0")/.." && pwd)/terraform/backend.hcl"

if aws s3api head-bucket --bucket "$BUCKET" 2>/dev/null; then
  echo "Bucket $BUCKET exists; re-applying settings."
else
  echo "Creating $BUCKET"
  if [ "$REGION" = us-east-1 ]; then
    aws s3api create-bucket --bucket "$BUCKET" --region "$REGION" >/dev/null
  else
    aws s3api create-bucket --bucket "$BUCKET" --region "$REGION" \
      --create-bucket-configuration "LocationConstraint=$REGION" >/dev/null
  fi
  aws s3api wait bucket-exists --bucket "$BUCKET"
fi

aws s3api put-public-access-block --bucket "$BUCKET" --public-access-block-configuration \
  BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true
aws s3api put-bucket-ownership-controls --bucket "$BUCKET" \
  --ownership-controls 'Rules=[{ObjectOwnership=BucketOwnerEnforced}]'
aws s3api put-bucket-versioning --bucket "$BUCKET" --versioning-configuration Status=Enabled
aws s3api put-bucket-encryption --bucket "$BUCKET" --server-side-encryption-configuration \
  '{"Rules":[{"ApplyServerSideEncryptionByDefault":{"SSEAlgorithm":"AES256"}}]}'
# Keep a year of old state versions; clean up abandoned multipart uploads.
aws s3api put-bucket-lifecycle-configuration --bucket "$BUCKET" --lifecycle-configuration '{
  "Rules":[{"ID":"state-history","Status":"Enabled","Filter":{},
    "NoncurrentVersionExpiration":{"NoncurrentDays":365},
    "AbortIncompleteMultipartUpload":{"DaysAfterInitiation":7}}]}' >/dev/null
aws s3api put-bucket-policy --bucket "$BUCKET" --policy "$(cat <<JSON
{"Version":"2012-10-17","Statement":[{"Sid":"DenyInsecureTransport","Effect":"Deny",
  "Principal":"*","Action":"s3:*",
  "Resource":["arn:aws:s3:::$BUCKET","arn:aws:s3:::$BUCKET/*"],
  "Condition":{"Bool":{"aws:SecureTransport":"false"}}}]}
JSON
)"
aws s3api put-bucket-tagging --bucket "$BUCKET" \
  --tagging "TagSet=[{Key=Project,Value=$NAME},{Key=Purpose,Value=terraform-state},{Key=Owner,Value=personal}]"

cat > "$BACKEND_FILE" <<HCL
# Generated by scripts/bootstrap-state-bucket.sh (gitignored). Used with:
#   terraform -chdir=terraform init -backend-config=backend.hcl -backend-config="profile=<your-profile>"
bucket = "$BUCKET"
key    = "$NAME/terraform.tfstate"
HCL

echo "Ready: s3://$BUCKET"
echo "Wrote $BACKEND_FILE"
